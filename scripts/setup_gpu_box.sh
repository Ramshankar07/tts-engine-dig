#!/usr/bin/env bash
# Set up a rented Linux CUDA box for P1. Each engine gets its OWN venv because
# their dependency stacks conflict (qwen-tts pins transformers 4.57.3; SGLang-Omni
# runs transformers 5.12 + shims; vLLM-Omni needs a matching vLLM build).
#
#   bash scripts/setup_gpu_box.sh            # everything
#   bash scripts/setup_gpu_box.sh vllm eval  # selected steps
#
# Steps: system model client official eval vllm sglang
# Writes $WORK/p1.env (sourced by the other scripts).
#
# Pins below are the versions/commits whose docs were read for this repo
# (docs/SOURCES.md). Bump them deliberately and record the change.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

# ----------------------------------------------------------------- pins
PY_VERSION="${PY_VERSION:-3.12}"
MODEL_ID="Qwen/Qwen3-TTS-12Hz-1.7B-CustomVoice"
MODEL_REVISION="${MODEL_REVISION:-0c0e3051f131929182e2c023b9537f8b1c68adfe}"
QWEN_TTS_VERSION="${QWEN_TTS_VERSION:-0.1.1}"
FLASH_ATTN_VERSION="${FLASH_ATTN_VERSION:-}"            # source build only; prefer OFFICIAL_TORCH=2.8.0 + FLASH_ATTN_WHEEL (prebuilt), as used for the measured runs
VLLM_OMNI_REF="${VLLM_OMNI_REF:-fa8b4199c6cece6f61dc5d8d990817d3555c70bc}"   # main @ 2026-10-13 (docs read here)
VLLM_VERSION="${VLLM_VERSION:-0.31.0}"                   # source checkout above targets vLLM 0.31.0
VLLM_WHEEL_INDEX="${VLLM_WHEEL_INDEX:-https://wheels.vllm.ai/db9527a46873454610df6dbedf79a36d6bf1a7f6}"
SGLANG_OMNI_REF="${SGLANG_OMNI_REF:-b880acf8f04fc782115c323cf2818b92241b063a}" # main @ 2026-10-13 (v0.1.8 released 2026-10-12)
UTMOSV2_REF="${UTMOSV2_REF:-cc2700db57bb83ee13dc31ebe1b868c254e15d09}"
# Alternative for stability: VLLM_OMNI_REF=v0.30.0 VLLM_VERSION=0.30.0 VLLM_WHEEL_INDEX= (PyPI wheels),
# SGLANG_OMNI_REF=v0.1.8. Re-check the request fields in docs/SOURCES.md if you do.

STEPS=("$@")
[[ ${#STEPS[@]} -eq 0 ]] && STEPS=(system model client official eval vllm sglang)
want() { local s; for s in "${STEPS[@]}"; do [[ "$s" == "$1" ]] && return 0; done; return 1; }

mkdir -p "$WORK" "$VENVS" "$SRC" "$(dirname "$MODEL_DIR")"

cat > "$ENV_FILE" <<EOF
# generated by setup_gpu_box.sh $(date -u +%FT%TZ)
export WORK="$WORK"
export VENVS="$VENVS"
export SRC="$SRC"
export MODEL_DIR="$MODEL_DIR"
export MODEL_REVISION="$MODEL_REVISION"
export VLLM_OMNI_REF="$VLLM_OMNI_REF"
export SGLANG_OMNI_REF="$SGLANG_OMNI_REF"
export QWEN_TTS_VERSION="$QWEN_TTS_VERSION"
EOF

checkout() {  # checkout URL DIR REF
  local url="$1" dir="$2" ref="$3"
  if [[ ! -d "$dir/.git" ]]; then git clone "$url" "$dir"; fi
  git -C "$dir" fetch --tags origin
  git -C "$dir" checkout --detach "$ref"
  log "$(basename "$dir") @ $(git -C "$dir" rev-parse HEAD)"
}

mkvenv() {  # mkvenv NAME -> prints python path
  local v="$VENVS/$1"
  [[ -x "$v/bin/python" ]] || uv venv "$v" -p "$PY_VERSION" >&2
  echo "$v/bin/python"
}

if want system; then
  log "system packages"
  if command -v apt-get >/dev/null; then
    SUDO=""; [[ $EUID -ne 0 ]] && SUDO="sudo"
    $SUDO apt-get update -y && $SUDO apt-get install -y git curl wget sox libsox-fmt-all libsndfile1 ffmpeg build-essential
  fi
  command -v uv >/dev/null || { curl -LsSf https://astral.sh/uv/install.sh | sh; export PATH="$HOME/.local/bin:$PATH"; }
  nvidia-smi || { log "nvidia-smi missing: this script needs a CUDA box"; exit 1; }
  command -v nsys >/dev/null && nsys --version || log "WARNING: nsys not found; install Nsight Systems for scripts/profile_nsys.sh"
fi

if want model; then
  log "downloading $MODEL_ID @ $MODEL_REVISION -> $MODEL_DIR"
  uvx --from huggingface_hub hf download "$MODEL_ID" --revision "$MODEL_REVISION" --local-dir "$MODEL_DIR"
fi

if want client; then
  # Light venv used to drive the HTTP engines (no torch).
  PY=$(mkvenv client)
  uv pip install --python "$PY" -e "$REPO"
fi

if want official; then
  PY=$(mkvenv official)
  # OFFICIAL_TORCH pins torch (e.g. 2.8.0) so a prebuilt flash-attn wheel exists;
  # FLASH_ATTN_WHEEL (URL) installs that wheel instead of compiling from source.
  uv pip install --python "$PY" --torch-backend="${TORCH_BACKEND:-auto}" -e "$REPO[official]" "qwen-tts==$QWEN_TTS_VERSION" \
    ${OFFICIAL_TORCH:+"torch==$OFFICIAL_TORCH" "torchaudio==$OFFICIAL_TORCH"}
  # FlashAttention 2 is recommended by the Qwen3-TTS README; the engine falls
  # back to sdpa if it is missing. Building can take a long time.
  uv pip install --python "$PY" setuptools wheel ninja packaging psutil
  if [[ -n "${FLASH_ATTN_WHEEL:-}" ]]; then
    uv pip install --python "$PY" "$FLASH_ATTN_WHEEL" || log "WARNING: flash-attn wheel install failed; official engine will use sdpa"
  else
  MAX_JOBS="${MAX_JOBS:-8}" uv pip install --python "$PY" --no-build-isolation "flash-attn${FLASH_ATTN_VERSION:+==$FLASH_ATTN_VERSION}" \
    || log "WARNING: flash-attn install failed; official engine will use sdpa (record this in the report)"
  fi
fi

if want eval; then
  PY=$(mkvenv eval)
  uv pip install --python "$PY" --torch-backend="${TORCH_BACKEND:-auto}" -e "$REPO[eval]"
  uv pip install --python "$PY" "git+https://github.com/sarulab-speech/UTMOSv2.git@$UTMOSV2_REF"
  # UTMOSv2 pulls PyPI torchvision/torchaudio, which can be built for a different
  # CUDA major than the torch above; reinstall them from the same backend.
  uv pip install --python "$PY" --torch-backend="${TORCH_BACKEND:-auto}" \
    --reinstall-package torchvision --reinstall-package torchaudio torchvision torchaudio
fi

if want vllm; then
  checkout https://github.com/vllm-project/vllm-omni.git "$SRC/vllm-omni" "$VLLM_OMNI_REF"
  PY=$(mkvenv vllm)
  if [[ -n "$VLLM_WHEEL_INDEX" ]]; then
    uv pip install --python "$PY" "vllm==$VLLM_VERSION" --torch-backend="${TORCH_BACKEND:-auto}" --extra-index-url "$VLLM_WHEEL_INDEX"
  else
    uv pip install --python "$PY" "vllm==$VLLM_VERSION" --torch-backend="${TORCH_BACKEND:-auto}"
  fi
  uv pip install --python "$PY" -e "$SRC/vllm-omni"
  uv pip install --python "$PY" ninja   # FlashInfer JIT (sampler) shells out to ninja
fi

if want sglang; then
  # Docs recommend the Docker image for CUDA (UCX/flash-attn prebuilt); this is
  # the documented source path. If it fails, use:
  #   docker pull hongccc/sglang-omni:dev   (pin by digest; record it in docs/SOURCES.md)
  checkout https://github.com/sgl-project/sglang-omni.git "$SRC/sglang-omni" "$SGLANG_OMNI_REF"
  PY=$(mkvenv sglang)
  uv pip install --python "$PY" --prerelease=allow -e "$SRC/sglang-omni"
  # Both --no-deps are required (cookbook): qwen-tts would replace transformers 5.12,
  # and resolving sox pulls numpy past numba's ceiling.
  uv pip install --python "$PY" --no-deps sox einops
  uv pip install --python "$PY" --no-deps "qwen-tts==$QWEN_TTS_VERSION"
  uv pip install --python "$PY" ninja
  # SGLang's DeepGEMM JIT needs nvcc >= 12.9 on PATH (CUDA 13.0 toolkit was used).
fi

log "done. env file: $ENV_FILE"
for v in "$VENVS"/*/; do
  if [[ -x "$v/bin/python" ]]; then log "venv $(basename "$v"): $("$v/bin/python" --version)"; fi
done
exit 0
